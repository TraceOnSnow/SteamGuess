const LANGUAGE_KEY = 'steamguess-language';
export type Language = 'zh' | 'en';

function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (saved === 'en' || saved === 'zh') return saved;
  } catch { /* Fall through to the browser language. */ }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

const language = initialLanguage();
if (typeof document !== 'undefined') document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';

void i18n.use(initReactI18next).init({
  resources: { zh: { translation: zh }, en: { translation: en } },
  lng: language,
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
  showSupportNotice: false,
});

export default i18n;

export function changeLanguage(next: Language) {
  void i18n.changeLanguage(next);
  try { localStorage.setItem(LANGUAGE_KEY, next); } catch { /* Optional preference. */ }
  document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
}
